'use strict'

const assert = require('assert')
const fs = require('fs')
const os = require('os')
const path = require('path')
const { execFileSync, spawnSync } = require('child_process')
const kit = require('../lib/bootstrap.cjs')
const ROOT = path.resolve(__dirname, '..')
const cli = path.join(ROOT, 'bin/knowledge-flywheel.cjs')
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'knowledge-kit-test-'))
let sequence = 0
let count = 0

function repo(name) {
  const root = path.join(temporary, `${++sequence}-${name}`)
  fs.mkdirSync(root)
  execFileSync('git', ['init', root], { stdio: 'ignore' })
  return fs.realpathSync(root)
}
function write(root, rel, text) { const file = path.join(root, rel); fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text) }
function read(root, rel) { return fs.readFileSync(path.join(root, rel), 'utf8') }
function exists(root, rel) { return fs.existsSync(path.join(root, rel)) }
function run(root, args) {
  const result = spawnSync(process.execPath, [cli, ...args, '--project', root], { encoding: 'utf8' })
  return { ...result, stdout: result.stdout || '', stderr: result.stderr || '' }
}
function ok(root, args) { const result = run(root, args); assert.strictEqual(result.status, 0, result.stderr); return JSON.parse(result.stdout) }
function rejected(root, args) { const result = run(root, args); assert.notStrictEqual(result.status, 0, result.stdout); return result }
function test(name, action) { action(); count += 1; console.log(`PASS ${name}`) }
function cloneSource() {
  const source = path.join(temporary, `source-${++sequence}`)
  fs.mkdirSync(source)
  for (const rel of ['package.json', 'templates', 'migrations']) fs.cpSync(path.join(ROOT, rel), path.join(source, rel), { recursive: true })
  return source
}

